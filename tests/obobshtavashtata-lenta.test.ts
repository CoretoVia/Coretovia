/**
 * ОБОБЩАВАЩАТА ЛЕНТА · родителят носи обхвата на децата си.
 *
 * Негово, 13.09 (запис 210), ДОСЛОВНО: „Обърни внимание да направиш **календара
 * да обхваща всички редове** и в Управлени и в Сметки." И 11.09 (запис 195 т.2):
 * „**Ганта обхваща всички редове изцяло** и се сливат двете."
 *
 * ЦЕНАТА, ПЛАТЕНА ДОТУК: Имотът, Обектът и Бизнесът нямаха НИТО ЕДНА клетка в
 * календара — лентата се смяташе само за задача, а родителят няма свои дати. И
 * кодът не го броеше: празният ред просто мълчеше през целия календар, тъй че
 * нищо не издаваше, че липсва. Задача без дата поне се КАЗВА; родителят не.
 *
 * Тук се пази поведението, което лесно се чупи тихо: обхватът се качва през
 * ВСИЧКИ отворени нива наведнъж (задачата влиза и в Обекта, и в Имота), а не
 * само в най-близкия си родител.
 */

import { describe, expect, it } from 'vitest';
import { obobshtenite, type RedZaObobshtavane } from '../src/smetach/gant.js';

/** Имот · неговият Обект · задачите под всеки · нивата са като в дървото. */
const DARVO: readonly RedZaObobshtavane[] = Object.freeze([
  { nivo: 0, ot: '', do: '' }, // 0 · Имот „Гара Яна"
  { nivo: 2, ot: '2026-03-01', do: '2026-03-10' }, // 1 · задача право под Имота
  { nivo: 1, ot: '', do: '' }, // 2 · Обект под него
  { nivo: 2, ot: '2026-01-15', do: '2026-02-01' }, // 3 · задача под Обекта · НАЙ-РАННА
  { nivo: 2, ot: '2026-05-01', do: '2026-06-30' }, // 4 · задача под Обекта · НАЙ-КЪСНА
  { nivo: 0, ot: '', do: '' }, // 5 · втори Имот, без нито едно дете
]);

describe('обобщаващата лента', () => {
  it('ИМОТЪТ обхваща всичко под себе си · и своите задачи, и тези на обектите му', () => {
    const o = obobshtenite(DARVO);
    expect(o.get(0)).toEqual({ ot: '2026-01-15', do: '2026-06-30' });
  });

  it('ОБЕКТЪТ обхваща само СВОИТЕ · задачата над него не влиза', () => {
    const o = obobshtenite(DARVO);
    // 2026-03-01 е задачата на Имота · тя стои ПРЕДИ обекта и не е негова
    expect(o.get(2)).toEqual({ ot: '2026-01-15', do: '2026-06-30' });
    expect(o.get(2)?.ot).not.toBe('2026-03-01');
  });

  it('РОДИТЕЛ БЕЗ ДЕЦА не получава лента · и не се преструва, че има', () => {
    const o = obobshtenite(DARVO);
    expect(o.has(5)).toBe(false);
  });

  it('ЗАДАЧАТА не е родител · тя не получава обхват от себе си', () => {
    const o = obobshtenite(DARVO);
    for (const i of [1, 3, 4]) expect(o.has(i)).toBe(false);
  });

  it('ред само с НАЧАЛО или само с КРАЙ пак разширява · липсата не е нула', () => {
    const samoNachalo = obobshtenite([
      { nivo: 0, ot: '', do: '' },
      { nivo: 2, ot: '2026-04-04', do: '' },
    ]);
    expect(samoNachalo.get(0)).toEqual({ ot: '2026-04-04', do: '2026-04-04' });
    const samoKray = obobshtenite([
      { nivo: 0, ot: '', do: '' },
      { nivo: 2, ot: '', do: '2026-04-04' },
    ]);
    expect(samoKray.get(0)).toEqual({ ot: '2026-04-04', do: '2026-04-04' });
  });

  it('ПРАЗЕН СПИСЪК дава празна карта · без хвърляне', () => {
    expect(obobshtenite([]).size).toBe(0);
  });

  it('ДВИЖЕНИЕТО също разширява · и парите са работа във времето', () => {
    // редът с пари влиза в дървото на ниво 2, като задачите (запис 193)
    const o = obobshtenite([
      { nivo: 0, ot: '', do: '' },
      { nivo: 2, ot: '2026-09-01', do: '' },
    ]);
    expect(o.get(0)).toEqual({ ot: '2026-09-01', do: '2026-09-01' });
  });

  it('ВТОРИЯТ ИМОТ не наследява децата на първия · стекът се затваря', () => {
    const o = obobshtenite([
      { nivo: 0, ot: '', do: '' },
      { nivo: 2, ot: '2026-01-01', do: '2026-01-02' },
      { nivo: 0, ot: '', do: '' },
      { nivo: 2, ot: '2026-12-01', do: '2026-12-02' },
    ]);
    expect(o.get(0)).toEqual({ ot: '2026-01-01', do: '2026-01-02' });
    expect(o.get(2)).toEqual({ ot: '2026-12-01', do: '2026-12-02' });
  });
});
