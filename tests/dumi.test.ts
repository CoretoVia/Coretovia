import { describe, expect, it } from 'vitest';
import { dumiZaGreshka, kolkoMyasto } from '../src/yadro/dumi.js';

describe('думите за човека', () => {
  it('грешка с име дава ИЗРЕЧЕНИЕТО си · без латинското име на класа', () => {
    class GreshkaVrata extends Error {}
    expect(dumiZaGreshka(new GreshkaVrata('Периодът е заключен.'))).toBe('Периодът е заключен.');
    // и никъде да не се промъкне името на класа
    expect(dumiZaGreshka(new GreshkaVrata('Периодът е заключен.'))).not.toContain('Greshka');
  });

  it('всичко, което НЕ е грешка, се казва както е', () => {
    expect(dumiZaGreshka('просто низ')).toBe('просто низ');
    expect(dumiZaGreshka(42)).toBe('42');
    expect(dumiZaGreshka(null)).toBe('null');
    expect(dumiZaGreshka(undefined)).toBe('undefined');
  });

  it('мястото се пише с БЪЛГАРСКА запетая · и с мярката си', () => {
    expect(kolkoMyasto(0)).toBe('0 Б');
    expect(kolkoMyasto(1023)).toBe('1023 Б');
    expect(kolkoMyasto(1024)).toBe('1,0 КБ');
    expect(kolkoMyasto(105_121)).toBe('102,7 КБ');
    expect(kolkoMyasto(3_481_600)).toBe('3,3 МБ');
    // НИТО ЕДНА точка · десетичният знак у нас е запетая (правило 15)
    expect(kolkoMyasto(3_481_600)).not.toContain('.');
  });

  it('липсващото число КАЗВА, че липсва · не показва нула', () => {
    // браузърът не винаги дава мярка · нулата тук би значела „нищо не е заето"
    expect(kolkoMyasto(-1)).toBe('—');
  });
});
