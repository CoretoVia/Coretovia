/**
 * ЕДИН РЕД НА ЕДНО НЕЩО · повторенията по месеци се събират в календара.
 *
 * Негово, 13.09 (запис 213), точка 2, ДОСЛОВНО: „**Редовете с една и съща Задача
 * или ред от сметки не се пренася в нов ред всеки месец, а това става в самия
 * календар където всеки ред минава през всеки такт**, ако етапа е по голям
 * събира всички за периода от реда в календара и го покзава в колона бюджет на
 * всеки ред."
 *
 * ЗАЩО Е НУЖНО. „Ток и вода" се въвежда всеки месец и всеки път е НОВ ред в
 * Журнала — така трябва, Журналът е само за добавяне и всяко плащане е свое
 * събитие. Но на екрана дванайсет реда „Ток и вода" под една секция не казват
 * нищо повече от един ред с дванайсет числа в календара; те само изяждат
 * таблицата и карат човек да брои сам.
 *
 * ГРУПИРАНЕТО Е ПОГЛЕД, НЕ ДАННИ. Нищо не се слива в Журнала, нищо не се пише,
 * нищо не се трие. Групата е начин на ГЛЕДАНЕ на едни и същи събития — затова
 * живее тук, в сметача, а не в Модела.
 *
 * КОЕ Е „ЕДНО И СЪЩО НЕЩО": еднакви родител · име · функция, в една секция. Два
 * реда с едно име, но различен Имот са различни неща и не се събират — инак
 * токът на две сгради би станал един ред и никой не би разбрал чий е.
 */

export interface RedZaGrupirane {
  readonly i: number;
  readonly id: string;
  readonly suma_st: number;
  readonly mesets: string;
  readonly data: string;
}

export interface Grupa<R extends RedZaGrupirane> {
  /** онова, по което редовете са едно и също нещо · за ключ и за проверка */
  readonly beleg: string;
  /** редът, който представя групата на екрана · най-ранният по дата */
  readonly parviyat: R;
  /** всички редове в групата, подредени по дата · и единственият е група от един */
  readonly redove: readonly R[];
  /** сборът на групата за подадените редове · цели центове, със знака */
  readonly sbor_st: number;
}

/**
 * Групите на едно множество редове · подредени както е дошъл първият им ред.
 *
 * `belegat` казва кое е едно и също нещо. Подава се отвън, защото името и
 * родителят идват от Огледалото, а тази функция не знае за него — тя брои.
 */
export function grupite<R extends RedZaGrupirane>(
  redove: readonly R[],
  belegat: (r: R) => string,
): readonly Grupa<R>[] {
  const po = new Map<string, R[]>();
  for (const r of redove) {
    const b = belegat(r);
    po.set(b, [...(po.get(b) ?? []), r]);
  }
  const izlaz: Grupa<R>[] = [];
  for (const [beleg, spisak] of po) {
    // по ДЕН, после по реда на създаване · два реда в един ден не си разменят местата
    const podredeni = [...spisak].sort((a, b) => {
      const da = a.data === '' ? `${a.mesets}-01` : a.data;
      const db = b.data === '' ? `${b.mesets}-01` : b.data;
      return da === db ? a.i - b.i : da < db ? -1 : 1;
    });
    izlaz.push({
      beleg,
      parviyat: podredeni[0]!,
      redove: podredeni,
      sbor_st: podredeni.reduce((a, r) => a + r.suma_st, 0),
    });
  }
  return izlaz;
}

/**
 * Колко реда е спестило групирането · за брояча под таблицата.
 *
 * Число, което казва „тези 40 реда се четат като 7" е разликата между подредба
 * и скриване: човек вижда, че нищо не е изчезнало (правило 12).
 */
export function spesteniRedove<R extends RedZaGrupirane>(grupi: readonly Grupa<R>[]): number {
  return grupi.reduce((a, g) => a + g.redove.length - 1, 0);
}
