import { deliZakragleno, sabiri, tsentove } from '../yadro/pari.js';
import type { Smetki } from './smetki.js';

/**
 * Само това, което Балансът наистина чете от Сметки.
 *
 * Тесният вход не е педантичност: така тестът може да сглоби Сметки от четири
 * полета, вместо да преписва целия им вид с `as`, а сглобеното с `as` мълчи,
 * когато утре видът порасне.
 */
export type SmetkiZaBalansa = Pick<Smetki, 'prihod' | 'razhod' | 'sborPrihod' | 'sborRazhod'>;

/** Един месец от записа · неговото „всеки месец запис колко е разликата". */
export interface MesetsNaBalansa {
  readonly mesets: string;
  /** цели центове · положително */
  readonly prihod: number;
  /** цели центове · отрицателно, както е записано (правило 16) */
  readonly razhod: number;
  /** приход + разход · положителното е печалба */
  readonly razlika: number;
}

export type Svetofar = 'zeleno' | 'zhalto' | 'cherveno';

export interface Balansat {
  /** цели центове · всичко, което държим ДНЕС · кеш + банка · НАТРУПАНО */
  readonly balans_st: number;
  /**
   * цели центове · вноските в БРОЙ по продажбите.
   *
   * Само те, не Общ Трезор: изтегленото е преместване, а раздаденото вече е
   * между движенията. Двете щяха да влязат втори път.
   */
  readonly vnoskiVBroy_st: number;
  /** цели центове · частта по банка · натрупана */
  readonly banka_st: number;
  /** цели центове · приход + разход САМО за периода на екрана */
  readonly zaPerioda_st: number;
  /** средната разлика приход − разход на месец В ПЕРИОДА · отрицателното яде баланса */
  readonly nameseets_st: number;
  /**
   * За колко месеца балансът се изчерпва при темпото на ПЕРИОДА.
   * `null`, когато разликата не е отрицателна — тогава не се изчерпва.
   */
  readonly mesetsiZhivot: number | null;
  readonly svetofar: Svetofar;
  /** защо свети така · с думи, за подсказката */
  readonly zashto: string;
  /** записът по месеци В ПЕРИОДА · неговото последно изречение от запис 203 */
  readonly mesetsi: readonly MesetsNaBalansa[];
}

/**
 * Под колко месеца живот е ОПАСНО · негово, запис 203: „разходите за 6 месеца".
 *
 * Това е ЕДИНСТВЕНИЯТ праг-число, което остана. Дванайсетте месеца от същия
 * запис си отидоха със запис 205: жълтото вече казва „на загуба си", а не
 * „парите ще свършат след по-малко от година".
 */
export const MESETSI_CHERVENO = 6;

/**
 * Разликата приход − разход за всеки месец, който има поне едно движение.
 *
 * Месец без нито едно движение не влиза: той не е „месец с нулева разлика", а
 * месец, за който не знаем нищо — да го броим би свалило средното без причина.
 */
export function mesetsiteNaBalansa(s: SmetkiZaBalansa): readonly MesetsNaBalansa[] {
  const po = new Map<string, { prihod: number; razhod: number }>();
  const vzemi = (m: string): { prihod: number; razhod: number } => {
    const x = po.get(m) ?? { prihod: 0, razhod: 0 };
    po.set(m, x);
    return x;
  };
  for (const sek of s.prihod) for (const r of sek.redove) vzemi(r.mesets).prihod += r.suma_st;
  for (const sek of s.razhod) for (const r of sek.redove) vzemi(r.mesets).razhod += r.suma_st;
  return [...po.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([mesets, x]) => ({
      mesets,
      prihod: x.prihod,
      razhod: x.razhod,
      razlika: x.prihod + x.razhod,
    }));
}

/**
 * @param vsichko   ВСИЧКИ Сметки · оттук идва натрупаният баланс
 * @param vPerioda  Сметките В ПЕРИОДА на екрана · оттук идва посоката и цветът
 * @param vnoskiVBroy_st Вноските в БРОЙ по продажбите · натрупани
 */
export function balansat(
  vsichko: SmetkiZaBalansa,
  vPerioda: SmetkiZaBalansa,
  vnoskiVBroy_st: number,
): Balansat {
  const mesetsi = mesetsiteNaBalansa(vPerioda);
  const banka_st = sabiri(tsentove(vsichko.sborPrihod), tsentove(vsichko.sborRazhod));
  const balans_st = sabiri(tsentove(vnoskiVBroy_st), tsentove(banka_st));
  const zaPerioda_st = sabiri(tsentove(vPerioda.sborPrihod), tsentove(vPerioda.sborRazhod));
  // средното се закръгля към цял цент · закръглянето на пари има ЕДИН дом
  // (правило 3 · `deliZakragleno`), и той пази знака при отрицателна разлика
  const nameseets_st = mesetsi.length === 0 ? 0 : deliZakragleno(zaPerioda_st, mesetsi.length);
  const mesetsiZhivot =
    nameseets_st >= 0 ? null : Math.max(0, Math.floor(balans_st / -nameseets_st));
  const opasno = balans_st < 0 || (mesetsiZhivot !== null && mesetsiZhivot < MESETSI_CHERVENO);
  const svetofar: Svetofar = opasno ? 'cherveno' : nameseets_st < 0 ? 'zhalto' : 'zeleno';
  return {
    balans_st,
    vnoskiVBroy_st,
    banka_st,
    zaPerioda_st,
    nameseets_st,
    mesetsiZhivot,
    svetofar,
    zashto: zashtoSveti(svetofar, mesetsiZhivot, balans_st),
    mesetsi,
  };
}

function zashtoSveti(s: Svetofar, mesetsiZhivot: number | null, balans_st: number): string {
  if (s === 'cherveno')
    return balans_st < 0
      ? 'ОПАСНО · балансът е под нулата: дължим повече, отколкото държим.'
      : `ОПАСНО · при темпото на този период парите стигат за ${String(mesetsiZhivot)} месеца — под шестте.`;
  if (s === 'zhalto')
    return mesetsiZhivot === null
      ? 'ЗАГУБА · разликата между приход и разход за периода е отрицателна.'
      : `ЗАГУБА за периода · при това темпо парите стигат за ${String(mesetsiZhivot)} месеца.`;
  return 'ПЕЧАЛБА · разликата между приход и разход за периода не яде баланса.';
}
