/**
 * ТРЕЗОРЪТ · всичко, което притежаваме в БРОЙ.
 *
 * Негово, 13.09 (запис 203), точка 4, ДОСЛОВНО: „**Трезора се пълни главно от
 * вноски СМР и те се трупат в него и показват само него, второ поле показва
 * Изтеглено(изтеглено по извлечение от Карта само). Това е всичко което
 * притежаваме Кеш и се дава в обща цифра и полето с име Общ Трезор.**"
 *
 * Оттам ТРИ числа и нито едно повече:
 *
 *   · **Трезор** — вноските в БРОЙ по продажбите (неговите „ПД смр" · „НС смр" ·
 *     „Акт 15 смр" · „ПД кеш" · „НС кеш"). Кои са те, не се решава тук: колоната
 *     носи `plashtane.strana === 'kesh'` в `osnova.ts`, и това е единственият им
 *     дом (правило 14). Трупат се през ВСИЧКИ продажби, не по месец — той казва
 *     „трупат се".
 *   · **Изтеглено** — изтегленото по банковото извлечение, също натрупано.
 *   · **Общ Трезор** — вноски + изтеглено − раздаденото в брой.
 *
 * ЗАЩО МИНУС РАЗДАДЕНОТО: „всичко което притежаваме Кеш" е това, което ОЩЕ е в
 * касата. Пари, дадени за заплати и фактури, са излезли; да стоят в Трезора би
 * значело да ги броим два пъти — веднъж като кеш, втори път като платен разход.
 *
 * ПРЕДИ 13.09 тук стояха други две числа — „в каса" (изтеглено − дадено) и „в
 * ръце" (дадено − вкарано), от `zadanie/CHISTO/06` M06-10. Второто вече е
 * невъзможно да не е нула: от този ден дадените пари СЕ СМЯТАТ от кеш секциите
 * (негово, т.3), тъй че „дадено − вкарано" е тъждество, а число, което не може
 * да не е нула, не е сверка — украса е. Първото остава, но в новото си име:
 * изтегленото е второто му поле.
 *
 * И M06-P3 важи както преди: „**Трезорът се СМЯТА, не се въвежда.**" Тук няма
 * нито едно поле за писане.
 */

import { sabiri, tsentove } from '../yadro/pari.js';
import type { Prodazhbite } from './prodazhbi.js';
import type { Kesh } from './smetki.js';

export interface Trezorat {
  /** цели центове · вноските в БРОЙ по всички продажби · те пълнят трезора */
  readonly vnoski_st: number;
  /** цели центове · изтеглено по извлечение · натрупано през всички месеци */
  readonly iztegleno_st: number;
  /** цели центове · раздаденото в брой · натрупано */
  readonly dadeno_st: number;
  /** цели центове · всичко, което притежаваме в брой */
  readonly obshto_st: number;
  /** думите под всяко число · какво го смята */
  readonly formulaNaVnoskite: string;
  readonly formulaNaIzteglenoto: string;
  readonly formulaNaObshtoto: string;
}

/**
 * `kesh` носи НАТРУПАНОТО (изтеглено и дадено през всички месеци), а не месеца
 * на екрана: Трезорът е каса, не отчет за месец.
 */
export function trezorat(kesh: Pick<Kesh, 'izvlechenie' | 'dadeno'>, p: Prodazhbite): Trezorat {
  const vnoski_st = sabiri(
    ...p.tablitsi.flatMap((t) =>
      t.redove.flatMap((r) =>
        r.strani.filter((s) => s.strana === 'kesh').map((s) => tsentove(s.vneseno)),
      ),
    ),
  );
  // раздаденото се чете ПО МОДУЛ · кеш секциите са РАЗХОД и се пазят с минус
  const dadeno_st = Math.abs(kesh.dadeno);
  return {
    vnoski_st,
    iztegleno_st: kesh.izvlechenie,
    dadeno_st,
    obshto_st: sabiri(tsentove(vnoski_st), tsentove(kesh.izvlechenie), tsentove(-dadeno_st)),
    formulaNaVnoskite: 'сборът на вноските в брой по всички продажби · те пълнят трезора',
    // НЕГОВО, 13.09 (запис 203), точка 4, ДОСЛОВНО: „второ поле показва
    // Изтеглено(изтеглено по извлечение от Карта САМО)." Кешът в ръка идва от
    // банкомат, тоест с КАРТАТА, и се вижда в нейното извлечение — Заданието го
    // казва отделно: „захранването с пари не пипа салдото на Карта" (M06-12), а
    // сверката по карта е на 5-о число от пълното извлечение (M06-19).
    //
    // Числото още се ВЪВЕЖДА на ръка, защото четецът на извлечения идва с ход
    // 11.3. Формулата го казва, вместо екранът да се преструва, че го е прочел.
    formulaNaIzteglenoto:
      'изтегленото в брой с КАРТАТА, по нейното извлечение · натрупано през всички ' +
      'месеци · още се въвежда на ръка: четенето на извлечения идва с ход 11.3',
    formulaNaObshtoto:
      'вноски в брой + изтеглено − раздадено в брой · всичко, което е още в касата',
  };
}
