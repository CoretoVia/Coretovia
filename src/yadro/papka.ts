/** Един файл в папката · толкова, колкото се вижда без да се отваря. */
export interface FaylVPapkata {
  readonly ime: string;
  /** байтове · -1, когато носителят не казва */
  readonly golyamina: number;
  /** ISO · кога е пипан последно · празно, когато носителят не казва */
  readonly promenen: string;
}

/** Какво знае програмата за папката на един ред. */
export interface PapkaNaReda {
  /** id на реда в своята таблица · Имот, Обект или Бизнес */
  readonly redId: string;
  /** името, което човекът вижда · името на самата папка */
  readonly ime: string;
  readonly faylove: readonly FaylVPapkata[];
  /**
   * ПОЗВОЛЕНИЕТО Е ОТДЕЛНО ОТ ВРЪЗКАТА.
   *
   * Браузърът помни коя папка е избрана, но при ново пускане иска потвърждение
   * наново. Тоест „прикачена" и „четима сега" са ДВЕ различни неща и програмата
   * не бива да ги бърка: първото е негово решение, второто е състояние на деня.
   */
  readonly chetima: boolean;
  /** празно, когато всичко е наред · инак КАЗВА защо не се чете (правило 12) */
  readonly zashtoNe: string;
}

/**
 * ПОРТЪТ · онова, което екранът иска от папките.
 *
 * Всяка връща `PapkaNaReda`, а не хвърля при отказ: отказът на човек („не избрах
 * папка") не е повреда и не бива да се лови с `try` на пет места.
 */
export interface PortaKamPapkite {
  /**
   * УМЕЕ ЛИ ИЗОБЩО · и защо е ТУК, а не при носителя.
   *
   * Екранът трябва да знае дали да рисува сив пункт, а `app/` няма право да
   * стига до `src/nositel` (слоевете го хванаха на 14.09, два пъти за един ден).
   * Питането е част от ДОГОВОРА: всеки носител сам казва какво може.
   */
  umee(): boolean;
  /** пита човека КОЯ папка · връща `null`, когато той откаже */
  prikachi(redId: string): Promise<PapkaNaReda | null>;
  /** чете НАНОВО онова, което вече е прикачено · това е „Обнови папките" */
  chetiPak(redId: string): Promise<PapkaNaReda | null>;
  /** всички прикачени, по ред на прикачване */
  spisak(): Promise<readonly PapkaNaReda[]>;
  /** маха ВРЪЗКАТА · файловете на диска не се пипат */
  otkachi(redId: string): Promise<void>;
  /** отваря един файл с програмата по подразбиране · `false`, когато не може */
  otvori(redId: string, ime: string): Promise<boolean>;
}

/**
 * КОЛКО ФАЙЛА И КОЛКО МЯСТО · за реда на екрана.
 *
 * Изнесено тук, защото и Управление, и бъдещото „Обнови папките" в Проверки
 * ще казват едно и също число, а два израза за един сбор се разминават
 * (правило 14).
 */
export function obobshtenieNaPapkata(p: PapkaNaReda | null): string {
  if (p === null) return 'няма прикачена папка';
  if (!p.chetima) return `${p.ime} · ${p.zashtoNe === '' ? 'чака потвърждение' : p.zashtoNe}`;
  const golyamina = p.faylove.reduce((a, f) => a + Math.max(f.golyamina, 0), 0);
  return `${p.ime} · ${String(p.faylove.length)} файла · ${String(golyamina)} Б`;
}
