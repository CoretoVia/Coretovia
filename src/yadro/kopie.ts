import type { Sabitie } from './sabitie.js';

/** Едно събитие — един ред. Завършва с нов ред, за да се дописва без шев. */
export function kopieNaZhurnala(sabitiya: readonly Sabitie[]): string {
  return sabitiya.map((s) => JSON.stringify(s)).join('\n') + (sabitiya.length > 0 ? '\n' : '');
}

/** Какво е намерено в един файл · и на кой ред се е спънало, ако се е спънало. */
export interface ProchetenoKopie {
  readonly sabitiya: readonly Sabitie[];
  /** празно, когато файлът е цял · инак КАЗВА къде и защо (правило 12) */
  readonly greshka: string;
  /** колко реда са прочетени, включително празните · за да не е сляпо числото */
  readonly redove: number;
}

/**
 * Чете копие · спъне ли се на ред, НИЩО не се връща.
 *
 * Половин Журнал е по-опасен от липсващ: Вратата би приела първите N събития за
 * цяла история и оттам нататък всяко ново събитие би стъпило върху отрязана
 * верига. Затова тук е всичко или нищо — същият закон, по който работи и самото
 * възстановяване.
 */
export function prochetiKopie(tekst: string): ProchetenoKopie {
  const redove = tekst.split('\n');
  const sabitiya: Sabitie[] = [];
  for (const [i, red] of redove.entries()) {
    const gol = red.trim();
    if (gol === '') continue;
    let razbrano: unknown;
    try {
      razbrano = JSON.parse(gol);
    } catch (e) {
      return {
        sabitiya: [],
        redove: redove.length,
        greshka: `Ред ${String(i + 1)} не е валиден JSON: ${e instanceof Error ? e.message : String(e)}`,
      };
    }
    if (typeof razbrano !== 'object' || razbrano === null || !('seq' in razbrano)) {
      return {
        sabitiya: [],
        redove: redove.length,
        greshka: `Ред ${String(i + 1)} не прилича на събитие: няма поле „seq".`,
      };
    }
    sabitiya.push(razbrano as Sabitie);
  }
  if (sabitiya.length === 0)
    return { sabitiya: [], redove: redove.length, greshka: 'Файлът няма нито едно събитие.' };
  return { sabitiya, redove: redove.length, greshka: '' };
}
