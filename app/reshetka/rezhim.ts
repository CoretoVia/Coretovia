/**
 * ДВАТА РЕЖИМА НА КАЛЕНДАРА · ЕДИН за Управление и за Сметки.
 *
 * Негово, 12.09 (запис 202), ДОСЛОВНО: „**Календара има две нива за които
 * говорихме. В едното състочние включват редовете с бюджет и редовете от
 * Сметки, а другото включва само Задачите без да се вкарва в календара
 * бюджета на всяко от тях което има.**" И: „**Двата бутона сменят и двата
 * режима в Управление и в Сметки.**"
 *
 * Оттам следват две неща, и второто е причината този файл да съществува:
 *
 *   · **ПАРИ** — в календара влизат числата: редовете от Сметки в Управление,
 *     секцията „Задачи с бюджет" в Сметки, и бюджетът в клетката на лентата.
 *   · **ЗАДАЧИ** — в календара остават само Задачите с текста си. Бюджетът не
 *     влиза нито в клетка, нито в сбора под нея; редовете от Сметки и секцията
 *     на задачите си отиват.
 *
 * И режимът е ЕДИН. Дотук всеки прозорец помнеше своя ключ
 * (`upravlenie.skriySmetki` и `smetki.skriyZadachi`) — два ключа за едно
 * решение, което той описва като едно. Затова ключът тук няма префикс на
 * прозорец: той не принадлежи на нито един от двата и не влиза в моделите им
 * (`snimkaNaEkrana` върви по префикс), защото именуван поглед на Управление
 * няма право да мени какво вижда Сметки.
 */

import { chetiEkranno, zapomniEkranno } from './pamet-ekran.js';

/** Кое ниво на календара се гледа · латински ключ, етикетът е на едно място. */
export type Rezhim = 'pari' | 'zadachi';

/** Ключът е ОБЩ · без префикс на прозорец, защото режимът не е ничий собствен. */
export const KLYUCHAT_NA_REZHIMA = 'rezhim';

/**
 * Подразбраното е ПАРИ: програмата е счетоводна и числото е причината да я има.
 * Скриването е негово ДЕЙСТВИЕ, не начално състояние.
 */
export function rezhimatSega(): Rezhim {
  return chetiEkranno<Rezhim>(KLYUCHAT_NA_REZHIMA, 'pari') === 'zadachi' ? 'zadachi' : 'pari';
}

/** Обръща режима и връща новия · един бутон, две състояния, нищо между тях. */
export function obarniRezhima(): Rezhim {
  const nov: Rezhim = rezhimatSega() === 'pari' ? 'zadachi' : 'pari';
  zapomniEkranno(KLYUCHAT_NA_REZHIMA, nov);
  return nov;
}

/** Влизат ли парите в календара · единственият въпрос, който екраните задават. */
export function parite(): boolean {
  return rezhimatSega() === 'pari';
}

/**
 * ЛИЦЕТО НА ЕДИНСТВЕНИЯ БУТОН · казва какво ще СТАНЕ, не какво е било.
 *
 * Негово, 13.09 (запис 210), ДОСЛОВНО: „СМетки отиват в Управление и Задачи
 * отива в СМеки **с по един бутон се пуска и изклюва добавянето**."
 *
 * Затова думата вече не е „Скрий/Покажи". Скриването е поглед — нещото е там,
 * но не се вижда; ДОБАВЯНЕТО е друго: чуждите редове или влизат в таблицата, или
 * не влизат изобщо. Разликата не е козметична, тя се вижда в числата: в Сметки
 * изваденото излиза и от сметката (негово, запис 163), а в Управление не мени
 * нищо там (запис 195 т.1).
 *
 * Двата прозореца въртят ЕДИН режим, но всеки назовава своето: Управление
 * вкарва „Сметки", Сметки вкарва „Задачи". Едно действие, две имена — на екрана
 * човек вижда своето, не общото.
 */
export function dumataNaRezhima(kakvo: string): string {
  return `${parite() ? 'Извади' : 'Вкарай'} ${kakvo}`;
}

/**
 * И СЪСТОЯНИЕТО, с думи · бутонът казва какво ще стане, редът под него — какво Е.
 *
 * Правило 12: изключеното се КАЗВА. Ако чуждите редове ги няма, човек трябва да
 * вижда защо ги няма, вместо да търси липсващото.
 */
export function sastoyanietoNaRezhima(kakvo: string): string {
  return parite() ? `${kakvo} са вътре` : `${kakvo} са извадени`;
}
